WITH historical_options AS (
    SELECT 'specialty'::VARCHAR(30) AS category, BTRIM(specialty)::VARCHAR(255) AS label FROM sales_call_activities
    UNION ALL SELECT 'department', BTRIM(department) FROM sales_call_activities
    UNION ALL SELECT 'group', BTRIM(customer_group) FROM sales_call_activities
    UNION ALL SELECT 'product', BTRIM(product_1) FROM sales_call_activities
    UNION ALL SELECT 'objective', BTRIM(objective) FROM sales_call_activities
    UNION ALL SELECT 'outcome', BTRIM(outcome) FROM sales_call_activities
    UNION ALL SELECT 'status', BTRIM(status) FROM sales_call_activities
), unique_historical_options AS (
    SELECT category, MIN(label) AS label
    FROM historical_options
    WHERE label IS NOT NULL AND label <> ''
    GROUP BY category, LOWER(label)
)
INSERT INTO sales_call_lookup_options (category, label, sort_order)
SELECT historical.category,
       historical.label,
       10000 + ROW_NUMBER() OVER (PARTITION BY historical.category ORDER BY historical.label) * 10
FROM unique_historical_options historical
WHERE NOT EXISTS (
    SELECT 1 FROM sales_call_lookup_options existing
    WHERE existing.category = historical.category
      AND LOWER(BTRIM(existing.label)) = LOWER(BTRIM(historical.label))
);

