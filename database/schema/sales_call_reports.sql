BEGIN;

CREATE TABLE IF NOT EXISTS sales_call_activities (
    call_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_user_id INTEGER NOT NULL REFERENCES users(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    seller_username VARCHAR(255) NOT NULL,
    activity_date DATE NOT NULL,
    activity_time TIME NULL,
    duration_minutes INTEGER NULL CHECK (duration_minutes IS NULL OR duration_minutes BETWEEN 0 AND 1440),
    customer_id INTEGER NULL,
    customer_name VARCHAR(500) NOT NULL,
    contact_name VARCHAR(255) NULL,
    contact_position VARCHAR(255) NULL,
    contact_phone VARCHAR(100) NULL,
    activity_type VARCHAR(50) NOT NULL CHECK (activity_type IN ('โทรศัพท์', 'เข้าพบ', 'ประชุมออนไลน์', 'อีเมล', 'LINE', 'อื่นๆ')),
    objective VARCHAR(100) NOT NULL CHECK (objective IN ('แนะนำบริษัท/สินค้า', 'ติดตามงาน', 'นำเสนอสินค้า', 'เสนอราคา', 'เจรจาต่อรอง', 'บริการหลังการขาย', 'เก็บข้อมูลตลาด', 'อื่นๆ')),
    outcome VARCHAR(100) NOT NULL CHECK (outcome IN ('ติดต่อสำเร็จ', 'นัดหมายครั้งถัดไป', 'ขอข้อมูลเพิ่มเติม', 'ขอใบเสนอราคา', 'ขอสินค้าทดลอง', 'ปิดการขายสำเร็จ', 'ยังไม่สนใจ', 'ติดต่อไม่ได้', 'ยกเลิก')),
    opportunity_stage VARCHAR(50) NOT NULL CHECK (opportunity_stage IN ('ลูกค้าเป้าหมาย', 'เริ่มติดต่อ', 'ค้นหาความต้องการ', 'นำเสนอ/เสนอราคา', 'เจรจาต่อรอง', 'ชนะการขาย', 'แพ้การขาย')),
    product_interest TEXT NULL,
    estimated_value NUMERIC(15, 2) NOT NULL DEFAULT 0 CHECK (estimated_value >= 0),
    actual_value NUMERIC(15, 2) NOT NULL DEFAULT 0 CHECK (actual_value >= 0),
    notes TEXT NULL,
    next_action TEXT NULL,
    next_follow_up_date DATE NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'เสร็จสิ้น' CHECK (status IN ('วางแผน', 'เสร็จสิ้น', 'ยกเลิก')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS sales_call_activities_seller_date_idx
    ON sales_call_activities (seller_user_id, activity_date DESC);
CREATE INDEX IF NOT EXISTS sales_call_activities_date_idx
    ON sales_call_activities (activity_date DESC);
CREATE INDEX IF NOT EXISTS sales_call_activities_stage_idx
    ON sales_call_activities (opportunity_stage, activity_date DESC);
CREATE INDEX IF NOT EXISTS sales_call_activities_follow_up_idx
    ON sales_call_activities (next_follow_up_date)
    WHERE next_follow_up_date IS NOT NULL AND status <> 'ยกเลิก';
CREATE INDEX IF NOT EXISTS sales_call_activities_customer_idx
    ON sales_call_activities (LOWER(BTRIM(customer_name)));

ALTER TABLE sales_call_activities
    ADD COLUMN IF NOT EXISTS call_no INTEGER,
    ADD COLUMN IF NOT EXISTS place_of_work VARCHAR(500),
    ADD COLUMN IF NOT EXISTS specialty VARCHAR(255),
    ADD COLUMN IF NOT EXISTS department VARCHAR(100),
    ADD COLUMN IF NOT EXISTS customer_group VARCHAR(100),
    ADD COLUMN IF NOT EXISTS product_1 VARCHAR(100),
    ADD COLUMN IF NOT EXISTS call_detail_objective TEXT,
    ADD COLUMN IF NOT EXISTS call_detail_outcome TEXT,
    ADD COLUMN IF NOT EXISTS sm_comment TEXT;

WITH numbered AS (
    SELECT call_id,
           ROW_NUMBER() OVER (PARTITION BY seller_user_id, activity_date ORDER BY call_id)::INTEGER AS number
    FROM sales_call_activities
    WHERE call_no IS NULL
)
UPDATE sales_call_activities AS calls
SET call_no = numbered.number
FROM numbered
WHERE calls.call_id = numbered.call_id;

ALTER TABLE sales_call_activities
    ALTER COLUMN call_no SET NOT NULL,
    ALTER COLUMN customer_name DROP NOT NULL,
    ALTER COLUMN activity_type SET DEFAULT 'เข้าพบ',
    ALTER COLUMN opportunity_stage SET DEFAULT 'เริ่มติดต่อ',
    ALTER COLUMN status SET DEFAULT 'ทำงาน';

ALTER TABLE sales_call_activities
    DROP CONSTRAINT IF EXISTS sales_call_activities_objective_check,
    DROP CONSTRAINT IF EXISTS sales_call_activities_outcome_check,
    DROP CONSTRAINT IF EXISTS sales_call_activities_status_check;

-- ค่า objective, outcome และ status จัดการจาก sales_call_lookup_options
-- จึงไม่ใช้ CHECK แบบรายการตายตัวซึ่งจะขัดขวางตัวเลือกใหม่จากหน้าเว็บ

CREATE UNIQUE INDEX IF NOT EXISTS sales_call_activities_daily_no_unique
    ON sales_call_activities (seller_user_id, activity_date, call_no);

COMMIT;
