-- Supabase new-table security template
--
-- This project normally accesses PostgreSQL from Laravel with a direct
-- connection. Use Pattern A unless a browser/mobile client must query the
-- table through Supabase REST or GraphQL.

-- ============================================================================
-- PATTERN A: backend-only table (project default)
-- ============================================================================

CREATE TABLE public.example_private_records (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

REVOKE ALL PRIVILEGES ON TABLE public.example_private_records
    FROM anon, authenticated, service_role;
REVOKE ALL PRIVILEGES ON SEQUENCE public.example_private_records_id_seq
    FROM anon, authenticated, service_role;

-- No RLS policy is required for Data API access because this object is not
-- reachable by a Data API role. Laravel's database role continues to work.

-- ============================================================================
-- PATTERN B: intentionally exposed to signed-in Supabase users
-- Replace the example table/column/policies with the real ownership model.
-- ============================================================================

CREATE TABLE public.example_user_records (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id uuid NOT NULL REFERENCES auth.users(id),
    body text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.example_user_records ENABLE ROW LEVEL SECURITY;

REVOKE ALL PRIVILEGES ON TABLE public.example_user_records
    FROM anon, authenticated, service_role;
REVOKE ALL PRIVILEGES ON SEQUENCE public.example_user_records_id_seq
    FROM anon, authenticated, service_role;

GRANT SELECT, INSERT, UPDATE, DELETE
    ON TABLE public.example_user_records TO authenticated;
GRANT USAGE, SELECT
    ON SEQUENCE public.example_user_records_id_seq TO authenticated;

CREATE POLICY example_user_records_select_own
    ON public.example_user_records
    FOR SELECT TO authenticated
    USING ((SELECT auth.uid()) = owner_id);

CREATE POLICY example_user_records_insert_own
    ON public.example_user_records
    FOR INSERT TO authenticated
    WITH CHECK ((SELECT auth.uid()) = owner_id);

CREATE POLICY example_user_records_update_own
    ON public.example_user_records
    FOR UPDATE TO authenticated
    USING ((SELECT auth.uid()) = owner_id)
    WITH CHECK ((SELECT auth.uid()) = owner_id);

CREATE POLICY example_user_records_delete_own
    ON public.example_user_records
    FOR DELETE TO authenticated
    USING ((SELECT auth.uid()) = owner_id);

