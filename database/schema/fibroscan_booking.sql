BEGIN;

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE IF NOT EXISTS fibroscan_machines (
    machine_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_code VARCHAR(50) NOT NULL,
    machine_name VARCHAR(255) NOT NULL,
    serial_number VARCHAR(255) NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'พร้อมใช้งาน'
        CHECK (status IN ('พร้อมใช้งาน', 'ซ่อมบำรุง', 'เลิกใช้งาน')),
    note TEXT NULL,
    created_by_user_id INTEGER NULL REFERENCES users(id) ON UPDATE CASCADE ON DELETE SET NULL,
    created_by VARCHAR(255) NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS fibroscan_machines_code_unique
    ON fibroscan_machines (LOWER(BTRIM(machine_code)));
CREATE UNIQUE INDEX IF NOT EXISTS fibroscan_machines_serial_unique
    ON fibroscan_machines (LOWER(BTRIM(serial_number)))
    WHERE serial_number IS NOT NULL AND BTRIM(serial_number) <> '';
CREATE INDEX IF NOT EXISTS fibroscan_machines_status_idx
    ON fibroscan_machines (status, machine_code);

CREATE TABLE IF NOT EXISTS fibroscan_bookings (
    booking_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id BIGINT NOT NULL REFERENCES fibroscan_machines(machine_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    hospital_name VARCHAR(500) NOT NULL,
    purpose VARCHAR(100) NOT NULL
        CHECK (purpose IN ('ทดลองใช้', 'Event', 'เช่า', 'สาธิต', 'อื่นๆ')),
    reserved_from TIMESTAMPTZ NOT NULL,
    reserved_until TIMESTAMPTZ NOT NULL,
    contact_name VARCHAR(255) NULL,
    contact_phone VARCHAR(100) NULL,
    note TEXT NULL,
    approval_status VARCHAR(30) NOT NULL DEFAULT 'อนุมัติแล้ว'
        CHECK (approval_status IN ('รออนุมัติ', 'อนุมัติแล้ว', 'ไม่อนุมัติ')),
    reviewed_by_user_id INTEGER NULL REFERENCES users(id) ON UPDATE CASCADE ON DELETE SET NULL,
    reviewed_by VARCHAR(255) NULL,
    reviewed_at TIMESTAMPTZ NULL,
    review_note TEXT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'จองแล้ว'
        CHECK (status IN ('จองแล้ว', 'กำลังใช้งาน', 'คืนแล้ว', 'ยกเลิก')),
    booked_by_user_id INTEGER NOT NULL REFERENCES users(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    booked_by VARCHAR(255) NOT NULL,
    booked_by_department VARCHAR(255) NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (reserved_until > reserved_from)
);

-- Upgrade existing installations without changing historical bookings.
ALTER TABLE fibroscan_bookings
    ADD COLUMN IF NOT EXISTS approval_status VARCHAR(30) NOT NULL DEFAULT 'อนุมัติแล้ว',
    ADD COLUMN IF NOT EXISTS reviewed_by_user_id INTEGER NULL REFERENCES users(id) ON UPDATE CASCADE ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS reviewed_by VARCHAR(255) NULL,
    ADD COLUMN IF NOT EXISTS reviewed_at TIMESTAMPTZ NULL,
    ADD COLUMN IF NOT EXISTS review_note TEXT NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fibroscan_bookings_approval_status_check'
          AND conrelid = 'fibroscan_bookings'::regclass
    ) THEN
        ALTER TABLE fibroscan_bookings
            ADD CONSTRAINT fibroscan_bookings_approval_status_check
            CHECK (approval_status IN ('รออนุมัติ', 'อนุมัติแล้ว', 'ไม่อนุมัติ'));
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS fibroscan_booking_changes (
    change_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES fibroscan_bookings(booking_id) ON UPDATE CASCADE ON DELETE CASCADE,
    changed_by_user_id INTEGER NULL REFERENCES users(id) ON UPDATE CASCADE ON DELETE SET NULL,
    changed_by VARCHAR(255) NOT NULL,
    action VARCHAR(50) NOT NULL,
    changes JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS fibroscan_bookings_period_idx
    ON fibroscan_bookings (reserved_from, reserved_until);
CREATE INDEX IF NOT EXISTS fibroscan_bookings_machine_period_idx
    ON fibroscan_bookings (machine_id, reserved_from, reserved_until);
CREATE INDEX IF NOT EXISTS fibroscan_bookings_owner_idx
    ON fibroscan_bookings (booked_by_user_id, reserved_from DESC);
CREATE INDEX IF NOT EXISTS fibroscan_bookings_approval_idx
    ON fibroscan_bookings (approval_status, reserved_from);
CREATE INDEX IF NOT EXISTS fibroscan_booking_changes_booking_idx
    ON fibroscan_booking_changes (booking_id, change_id DESC);

-- Pending/rejected requests do not reserve a machine. Rebuild the exclusion
-- rule so only approved, active bookings can block the same time range.
ALTER TABLE fibroscan_bookings
    DROP CONSTRAINT IF EXISTS fibroscan_bookings_no_active_overlap;
ALTER TABLE fibroscan_bookings
    ADD CONSTRAINT fibroscan_bookings_no_active_overlap
    EXCLUDE USING gist (
        machine_id WITH =,
        tstzrange(reserved_from, reserved_until, '[)') WITH &&
    )
    WHERE (approval_status = 'อนุมัติแล้ว' AND status IN ('จองแล้ว', 'กำลังใช้งาน'));

COMMIT;
